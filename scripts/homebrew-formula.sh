#!/usr/bin/env bash
# Print the Homebrew formula for a release, for the Spheroman/homebrew-newgit tap.
#
#   scripts/homebrew-formula.sh 0.6.0 artifacts/ > Formula/newgit.rb
#
# The directory holds the release's `newgit-<target>.tar.gz.sha256` files, so
# the formula pins exactly the archives that were published. The release
# workflow runs this after publishing; run it by hand to repair the tap.
set -euo pipefail

if [ $# -ne 2 ]; then
  echo "usage: $0 <version> <dir with newgit-<target>.tar.gz.sha256>" >&2
  exit 2
fi
version="${1#v}"
dir="$2"
base="https://github.com/Spheroman/newgit/releases/download/v$version"

sha() {
  local file="$dir/newgit-$1.tar.gz.sha256"
  if [ ! -s "$file" ]; then
    echo "missing $file" >&2
    exit 1
  fi
  local hex
  hex="$(cut -d' ' -f1 <"$file")"
  if ! [[ "$hex" =~ ^[0-9a-f]{64}$ ]]; then
    echo "$file does not hold a sha256" >&2
    exit 1
  fi
  echo "$hex"
}

# Resolve every checksum before printing, so a missing one fails the script
# instead of leaving a half-written formula behind a redirect.
mac_arm="$(sha aarch64-apple-darwin)"
mac_intel="$(sha x86_64-apple-darwin)"
linux_arm="$(sha aarch64-unknown-linux-musl)"
linux_intel="$(sha x86_64-unknown-linux-musl)"

cat <<EOF
# Generated by scripts/homebrew-formula.sh in Spheroman/newgit; edits here are
# overwritten by the next release.
class Newgit < Formula
  desc "Every branch, ready to run"
  homepage "https://github.com/Spheroman/newgit"
  version "$version"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$base/newgit-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "$base/newgit-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "$base/newgit-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "$base/newgit-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
  end

  uses_from_macos "git"

  def install
    bin.install "newgit"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/newgit --version")
  end
end
EOF
